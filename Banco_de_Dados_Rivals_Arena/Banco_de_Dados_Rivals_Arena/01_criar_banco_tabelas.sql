CREATE DATABASE IF NOT EXISTS rivals_arena_front

USE rivals_arena_front;

SET FOREIGN_KEY_CHECKS = 0;
CHARACTER SET utf8mb4
COLLATE utf8mb4_unicode_ci;

USE rivals_arena_front;

SET FOREIGN_KEY_CHECKS = 0;

DROP TABLE IF EXISTS Publicacaos;
DROP TABLE IF EXISTS Partidas;
DROP TABLE IF EXISTS Inscricaos;
DROP TABLE IF EXISTS Usuarios;
DROP TABLE IF EXISTS Campeonatos;
DROP TABLE IF EXISTS Jogos;
DROP TABLE IF EXISTS Times;

SET FOREIGN_KEY_CHECKS = 1;

SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE Times (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(40) NOT NULL UNIQUE,
  tag VARCHAR(5) NOT NULL,
  jogo VARCHAR(40) NOT NULL,
  descricao VARCHAR(300),
  pontos INT DEFAULT 0,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE Usuarios (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nick VARCHAR(30) NOT NULL UNIQUE,
  email VARCHAR(120) NOT NULL UNIQUE,
  senha VARCHAR(255) NOT NULL,
  jogo VARCHAR(40) DEFAULT 'Valorant',
  pontos INT DEFAULT 0,
  vitorias INT DEFAULT 0,
  derrotas INT DEFAULT 0,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  TimeId INT NULL,
  FOREIGN KEY (TimeId) REFERENCES Times(id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB;

CREATE TABLE Campeonatos (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(80) NOT NULL,
  jogo VARCHAR(40) NOT NULL,
  status ENUM('aberto','andamento','encerrado') DEFAULT 'aberto',
  premio VARCHAR(40),
  vagas INT DEFAULT 16,
  dataInicio DATE,
  descricao VARCHAR(400),
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE Inscricaos (
  id INT AUTO_INCREMENT PRIMARY KEY,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  TimeId INT NULL,
  CampeonatoId INT NULL,
  FOREIGN KEY (TimeId) REFERENCES Times(id) ON DELETE SET NULL ON UPDATE CASCADE,
  FOREIGN KEY (CampeonatoId) REFERENCES Campeonatos(id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB;

CREATE TABLE Partidas (
  id INT AUTO_INCREMENT PRIMARY KEY,
  placarA INT DEFAULT 0,
  placarB INT DEFAULT 0,
  status ENUM('agendada','ao_vivo','finalizada') DEFAULT 'agendada',
  dataHora DATETIME,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CampeonatoId INT NULL,
  timeAId INT NULL,
  timeBId INT NULL,
  FOREIGN KEY (CampeonatoId) REFERENCES Campeonatos(id) ON DELETE SET NULL ON UPDATE CASCADE,
  FOREIGN KEY (timeAId) REFERENCES Times(id) ON DELETE SET NULL ON UPDATE CASCADE,
  FOREIGN KEY (timeBId) REFERENCES Times(id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB;

CREATE TABLE Publicacaos (
  id INT AUTO_INCREMENT PRIMARY KEY,
  texto VARCHAR(500) NOT NULL,
  categoria VARCHAR(20) DEFAULT 'geral',
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UsuarioId INT NULL,
  FOREIGN KEY (UsuarioId) REFERENCES Usuarios(id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB;

CREATE TABLE Jogos (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(40) NOT NULL UNIQUE,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
